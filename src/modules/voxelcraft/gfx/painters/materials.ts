// Тайлы этапа выживания: руды и глубинный сланец, блоки хранения, материалы (слитки, самоцветы,
// пыль), инструменты всех уровней и броня. Инструменты и броня — один шаблон формы на тип,
// перекрашенный палитрой материала.
import {
  P,
  PAINTERS,
  TILE,
  noisy,
  oreBlobs,
  shade,
  type Painter,
} from "../paint";

/** Порядок тайлов этой части в атласе (TextureAtlas дописывает его в TILE_ORDER). */
export const MATERIAL_TILES: string[] = [];

const add = (name: string, p: Painter): void => {
  PAINTERS[name] = p;
  MATERIAL_TILES.push(name);
};

// ---- руды и породы -------------------------------------------------------------------

/** Камень с вкраплениями руды (камень рисуется в момент сборки атласа — он уже в реестре). */
const stoneWith =
  (color: string): Painter =>
  (px, rng) => {
    PAINTERS.stone!(px, rng);
    oreBlobs(px, rng, color);
  };

add("copper_ore", stoneWith("#c9743e"));
add("gold_ore", stoneWith("#f5d23c"));
add("redstone_ore", stoneWith("#d21818"));
add("lapis_ore", stoneWith("#1f4fbf"));
add("diamond_ore", stoneWith("#5ae8dc"));
add("emerald_ore", stoneWith("#2fd05a"));

add("deepslate", (px, rng) => {
  noisy(px, "#4d4d52", 0.07, rng);
  for (let y = 1; y < TILE; y += 4)
    for (let x = 0; x < TILE; x++)
      if (rng() < 0.7) px(x, y, shade("#393940", (rng() - 0.5) * 0.1));
});
add("cobbled_deepslate", (px, rng) => {
  noisy(px, "#4a4a4e", 0.1, rng);
  for (let y = 0; y < TILE; y++)
    for (let x = 0; x < TILE; x++) {
      const seam = (x + (y & 4 ? 3 : 0)) % 5 === 0 || y % 5 === 0;
      if (seam && rng() < 0.85) px(x, y, shade("#2a2a2e", (rng() - 0.5) * 0.2));
    }
});

// ---- блоки хранения --------------------------------------------------------------------

/** Блок из девяти слитков/самоцветов: ровная заливка, светлая кромка сверху-слева, тёмная снизу-справа. */
const storage =
  (base: string, light: string, dark: string): Painter =>
  (px, rng) => {
    noisy(px, base, 0.05, rng);
    for (let i = 0; i < TILE; i++) {
      px(i, 0, light);
      px(0, i, light);
      px(i, 15, dark);
      px(15, i, dark);
    }
    for (let i = 3; i < 13; i += 3) {
      px(i, 4, light);
      px(i + 1, 11, dark);
    }
  };

add("coal_block", storage("#1c1c1c", "#3a3a3a", "#0a0a0a"));
add("iron_block", storage("#d8d8d8", "#ffffff", "#9a9a9a"));
add("copper_block", storage("#c06a3e", "#e89a6a", "#8a4424"));
add("gold_block", storage("#f2c93c", "#fff08a", "#b08a18"));
add("redstone_block", storage("#b01818", "#e84848", "#6a0808"));
add("lapis_block", storage("#2848a8", "#5a7ae0", "#142870"));
add("diamond_block", storage("#5ee8dc", "#c8fff8", "#1f9e94"));
add("emerald_block", storage("#2fcf5a", "#8affa8", "#127a30"));

