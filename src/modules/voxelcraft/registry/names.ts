/** Название для интерфейса; нет в таблице — id без подчёркиваний. */
export function labelOf(id: string): string {
  return NAMES[id] ?? id.replace(/_/g, " ");
}

/** Дописать названия (части реестра, сгенерированные из таблиц видов). */
