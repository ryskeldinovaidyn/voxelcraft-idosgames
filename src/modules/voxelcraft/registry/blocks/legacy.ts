import type { BlockDef } from "../../types";
import { all, block, pillar } from "./define";

/** Цветная шерсть: мягкий блок, быстрее ножницами, тайл рисуется по цвету. */
const wool = (id: number, name: string, color: number): BlockDef =>
  block({
    id,
    name,
    hardness: 0.8,
    tool: "shears",
    flammable: true,
    tex: all(name),
    mapColor: color,
  });

/** Растение-крестовина: без коллизии, ломается мгновенно, горит. */
const plant = (
  id: number,
  name: string,
  mapColor: number,
  extra: Partial<BlockDef> = {},
): BlockDef =>
  block({
    id,
    name,
    solid: false,
    opaque: false,
    cross: true,
    hardness: 0,
    flammable: true,
    tex: { side: name },
    mapColor,
    ...extra,
  });

