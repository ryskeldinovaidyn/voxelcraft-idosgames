const HERD = { light: "bright", ground: ["grass"], group: [2, 4] } as const;

/** Четыре ноги: диагональные пары шагают вместе (legL — перед-лево и зад-право). */
function legs(
  w: number,
  h: number,
  x: number,
  zFront: number,
  zBack: number,
  color: string,
): MobPart[] {
  return [
    {
      name: "legFL",
      size: [w, h, w],
      pos: [-x, h / 2, zFront],
      pivot: [-x, h, zFront],
      anim: "legL",
      color,
    },
    {
      name: "legFR",
      size: [w, h, w],
      pos: [x, h / 2, zFront],
      pivot: [x, h, zFront],
      anim: "legR",
      color,
    },
    {
      name: "legBL",
      size: [w, h, w],
      pos: [-x, h / 2, zBack],
      pivot: [-x, h, zBack],
      anim: "legR",
      color,
    },
    {
      name: "legBR",
      size: [w, h, w],
      pos: [x, h / 2, zBack],
      pivot: [x, h, zBack],
      anim: "legL",
      color,
    },
  ];
}

