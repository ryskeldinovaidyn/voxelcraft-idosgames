// появляются в толще воды — spawn.medium). Спрут роняет чернильный мешок — чёрный краситель.
import type { MobDef, MobPart } from "../../types";

function legs(
  w: number,
  h: number,
  x: number,
  zFront: number,
  zBack: number,
  color: string,
): MobPart[] {
  const leg = (
    name: string,
    lx: number,
    z: number,
    anim: "legL" | "legR",
  ): MobPart => ({
    name,
    size: [w, h, w],
    pos: [lx, h / 2, z],
    pivot: [lx, h, z],
    anim,
    color,
  });
  return [
    leg("legFL", -x, zFront, "legL"),
    leg("legFR", x, zFront, "legR"),
    leg("legBL", -x, zBack, "legR"),
    leg("legBR", x, zBack, "legL"),
  ];
}

