const BUILT_IN: Record<string, [Key, Key]> = {
  "system.gift": ["sysGiftSubject", "sysGiftBody"],
  "system.transfer": ["sysTransferSubject", "sysTransferBody"],
  "system.transfer_return": [
    "sysTransferReturnSubject",
    "sysTransferReturnBody",
  ],
  "system.leaderboard_reward": ["sysLeaderboardSubject", "sysLeaderboardBody"],
  "system.coop_grand_prize": ["sysCoopGrandSubject", "sysCoopGrandBody"],
  "system.coop_object_reward": ["sysCoopObjectSubject", "sysCoopObjectBody"],
  "system.season_unclaimed": ["sysSeasonSubject", "sysSeasonBody"],
  "system.referral_reward": ["sysReferralSubject", "sysReferralBody"],
};

/** Texts of the platform's own templates (a letter of a publisher's template carries its own). */
export function builtInText(templateID: string): LetterText | null {
  const keys = BUILT_IN[templateID];
  return keys ? { subject: t(keys[0]), body: t(keys[1]) } : null;
}

/** A server code in the player's words; any other error as the kit shows it. */
export function mailError(error: string | null | undefined): string | null {
  const code = (error ?? "").trim();
  const key = `err${code}` as Key;
  return code && key in EN ? t(key) : null;
}
